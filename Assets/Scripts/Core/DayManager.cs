    static T[] LoadAll<T>() where T : Object =>
        UnityEditor.AssetDatabase.FindAssets("t:" + typeof(T).Name)
            .Select(g => UnityEditor.AssetDatabase.LoadAssetAtPath<T>(UnityEditor.AssetDatabase.GUIDToAssetPath(g)))
            .ToArray();
