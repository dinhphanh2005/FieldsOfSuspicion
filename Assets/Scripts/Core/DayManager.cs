    void ShowMainMenu()
    {
        foreach (var panel in new[] { newsPanel, morningPanel, afternoonPanel, nightPanel, endingPanel, notebookPanel })
            if (panel) panel.SetActive(false);
        if (hud) hud.gameObject.SetActive(false);
        menuRoot.gameObject.SetActive(true);
        settingsRoot.gameObject.SetActive(false);
        var continueButton = menuRoot.GetComponentsInChildren<Button>(true).FirstOrDefault(b => b.name == "Continue");
        if (continueButton) UIFactory.SetInteractable(continueButton, SaveSystem.HasSave);
    }

    void OpenSettings()
    {
        menuRoot.gameObject.SetActive(false);
        settingsRoot.gameObject.SetActive(true);
        RefreshSettings();
    }

    void CloseSettings()
    {
        settingsRoot.gameObject.SetActive(false);
        menuRoot.gameObject.SetActive(true);
    }

    void ToggleFullscreen()
    {
        Screen.fullScreen = !Screen.fullScreen;
        PlayerPrefs.SetInt("FoS.Fullscreen", Screen.fullScreen ? 1 : 0);
        PlayerPrefs.Save();
        RefreshSettings();
    }

    void ChangeVolume(float delta)
    {
        AudioListener.volume = Mathf.Clamp01(AudioListener.volume + delta);
        PlayerPrefs.SetFloat("FoS.Volume", AudioListener.volume);
        PlayerPrefs.Save();
        RefreshSettings();
    }

    void CycleResolution()
    {
        var resolutions = Screen.resolutions;
        if (resolutions == null || resolutions.Length == 0) return;
        int current = System.Array.FindIndex(resolutions, r => r.width == Screen.width && r.height == Screen.height);
        var next = resolutions[(current + 1 + resolutions.Length) % resolutions.Length];
        var mode = Screen.fullScreen ? FullScreenMode.FullScreenWindow : FullScreenMode.Windowed;
        Screen.SetResolution(next.width, next.height, mode, next.refreshRateRatio);
        PlayerPrefs.SetInt("FoS.Width", next.width);
        PlayerPrefs.SetInt("FoS.Height", next.height);
        PlayerPrefs.Save();
        RefreshSettings();
    }

    void RefreshSettings()
    {
        if (settingsSummary)
            settingsSummary.text = $"Màn hình: {Screen.width} × {Screen.height} · {(Screen.fullScreen ? "toàn màn hình" : "cửa sổ")}\nÂm lượng: {Mathf.RoundToInt(AudioListener.volume * 100)}%";
    }

    void StartNewGame()
    {
        menuFeedback.text = "";
        SaveSystem.DeleteSave();
        State = new GameState { day = 1, playerName = string.IsNullOrWhiteSpace(nameInput.text) ? "Wren" : nameInput.text.Trim() };
        BeginFromState();
    }

    void ContinueGame()
    {
        if (!SaveSystem.TryLoad(out var state, out var error))
        {
            menuFeedback.text = "Không thể tải bản lưu: " + error;
            return;
        }
        menuFeedback.text = "";
        State = state;
        BeginFromState();
    }

    void BeginFromState()
    {
        menuRoot.gameObject.SetActive(false);
        settingsRoot.gameObject.SetActive(false);
        if (hud) hud.gameObject.SetActive(true);
        EnterPhase(Phase.News);
    }

    void ApplySettings()
    {
        Screen.fullScreen = PlayerPrefs.GetInt("FoS.Fullscreen", 1) == 1;
        AudioListener.volume = PlayerPrefs.GetFloat("FoS.Volume", 1f);
        int width = PlayerPrefs.GetInt("FoS.Width", 0);
        int height = PlayerPrefs.GetInt("FoS.Height", 0);
        if (width > 0 && height > 0) Screen.SetResolution(width, height, Screen.fullScreen);
    }

    static void QuitGame()
    {
#if UNITY_EDITOR
        UnityEditor.EditorApplication.isPlaying = false;
#else
        Application.Quit();
#endif
    }

    public void EnterPhase(Phase phase)
    {
        CurrentPhase = phase;

        newsPanel.SetActive(phase == Phase.News);
        morningPanel.SetActive(phase == Phase.Morning);
        afternoonPanel.SetActive(phase == Phase.Afternoon);
        nightPanel.SetActive(phase == Phase.Night);
        endingPanel.SetActive(phase == Phase.Ended);
        notebookPanel.SetActive(false);

        switch (phase)
        {
            case Phase.News:
                if (newsTitle) newsTitle.text = $"TIN TỨC — {State.DayLabel}";
                if (!Today) Debug.LogWarning($"Chưa có DaySO cho N{State.day}");
                string letter = State.lastRentMissDay == State.day - 1 ? EconomyRules.RentLetter(State.rentWarnings) : null;
                var main = newsView.Show(Today, State, letter);
                // Tin tức có thể tự thêm mảnh tin vào sổ tay (F12 ở N6)
                if (main && !string.IsNullOrEmpty(main.grantsIntel)) CaptureIntel(main.grantsIntel);
                break;
            case Phase.Morning:
                if (State.growthProcessedDay != State.day)
                {
                    FarmSystem.GrowthTick(State, crops);
                    State.growthProcessedDay = State.day;
                }
                boardView.Show(Today, State); break;
            case Phase.Afternoon: shopView.Begin(Today);        break;
            case Phase.Night:     nightView.Begin();            break;
            case Phase.Resolve:   Resolve();                    break;
        }
    }

    // Gắn vào OnClick của các nút "Tiếp"
    public void EndPhase()
    {
        switch (CurrentPhase)
        {
            case Phase.News:      EnterPhase(Phase.Morning);   break;
            case Phase.Morning:   EnterPhase(Phase.Afternoon); break;
            case Phase.Afternoon: EnterPhase(Phase.Night);     break;
            case Phase.Night:     CompleteNight(null);         break;
        }
    }

    // NightView gọi khi người chơi bấm "Đi" (drop != null) hoặc "Ở nhà tối nay" (drop == null).
    // Điểm nghi ngờ của đoạn đường đã được NightView cộng trước khi gọi hàm này.
    public void CompleteNight(DropRecord drop)
    {
        if (drop != null)
        {
            State.deliveredDrops.Add(drop);
            GameEvents.RaiseDropDelivered(drop);

            var delivered = FindIntel(drop.intelId);
            if (delivered && drop.mode == DeliveryMode.Truthful)
            {
                State.AddSuspicion(delivered.leakChannel, delivered.leakSuspicion, $"tin {drop.intelId} rò rỉ");
                var evidence = State.intelEvidence.Find(e => e.intelId == drop.intelId);
                if (evidence != null) evidence.consequenceSpreading = true;
            }
            else if (delivered && drop.mode == DeliveryMode.False)
                State.AddSuspicion(SuspicionChannel.Patrol, 1, "giao tin giả");
        }
        EnterPhase(Phase.Resolve);
    }

    // Trả tiền nhà ở Tổng kết. Thiếu tiền: không trừ, ghi một lần thiếu (thư nhắc sáng mai).
    void PayRent()
    {
        if (RentSystem.Settle(State))
        {
            Debug.Log($"[Tiền nhà] -{EconomyRules.Rent} xu, còn {State.money}");
        }
        else
        {
            Debug.Log($"[Tiền nhà] Thiếu tiền nhà lần {State.rentWarnings}");
        }
    }

    void Resolve()
    {
        PayRent();
        if (State.shopOpenedToday)
            State.customerBaseMomentum = PricingSystem.MomentumAfterDay(State.customerBaseMomentum, State.shopPriceLevel, State.salesToday);
        State.CloseNight();
        if (BurnPredictor.TryPredict(State, burnModelWeights, burnModelBias, out float probability))
            State.burnProbability = probability;
        Debug.Log($"[Nghi ngờ] Tổng kết N{State.day}: đêm nay {State.nightlySuspicion[State.nightlySuspicion.Count - 1]}, " +
                  $"cửa sổ {SuspicionRules.WindowNights} đêm = {State.SuspicionWindow} / {SuspicionRules.BurnThreshold}, " +
                  $"cộng dồn = {State.SuspicionTotal}");
        GameEvents.RaiseDayResolved(State.day);
        State.ReconcileEvidence();
        HandlerOrderEvaluator.ResolveDay(State, Today, days);

        var ending = EndingResolver.Resolve(State);
        if (ending.HasValue)
        {
            State.ending = ending.Value.ToString();
            GameEvents.RaiseEndingReached(ending.Value);
            telemetry.WriteDayRow(State);
            EnterPhase(Phase.Ended);                         // bật panel trước để layout đo được chữ
            endingView.Show(FindEnding(ending.Value), State);
            return;
        }

        telemetry.WriteDayRow(State);
        State.NextDay();
        if (!SaveSystem.AutoSave(State, out var saveError)) Debug.LogWarning("Tự lưu thất bại: " + saveError);
        EnterPhase(Phase.News);
    }

    public void CaptureIntel(string id)
    {
        if (!State.AddFragment(id)) return;
        if (!State.capturedToday.Contains(id)) State.capturedToday.Add(id);
        State.ReconcileEvidence();
        GameEvents.RaiseIntelCaptured(id);
    }

    public IntelSO FindIntel(string id) =>
        intel == null ? null : System.Array.Find(intel, i => i && i.id == id);

    public CropSO FindCrop(string id) => crops == null ? null : System.Array.Find(crops, c => c && c.id == id);

    EndingSO FindEnding(EndingId id) =>
        endings == null ? null : System.Array.Find(endings, e => e && e.id == id);

    public void OpenNotebook()
    {
        notebookView.Refresh();
        notebookPanel.SetActive(true);
    }

    public void CloseNotebook() => notebookPanel.SetActive(false);
}
