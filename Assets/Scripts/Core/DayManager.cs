    static T[] Clean<T>(T[] arr) where T : Object => arr == null ? null : arr.Where(x => x).ToArray();

    static T Ensure<T>(GameObject go) where T : Component
    {
        var c = go.GetComponent<T>();
        return c ? c : go.AddComponent<T>();
    }

